import type { Classification } from './classifier';

/**
 * Tracker-neutral bug draft. GitHub Issues, Jira or Linear adapters consume
 * this shape; none of them is called automatically. Status is always "draft"
 * until a human reviews it.
 */
export interface BugDraft {
  schemaVersion: 1;
  /** Test run that produced this draft; evidence lives in evidence/runs/<runId>/. */
  runId: string;
  status: 'draft';
  fingerprint: string;
  title: string;
  testCaseIds: string[];
  linkedBugs: string[];
  classification: Classification;
  severity: { suggested: 'critical' | 'major' | 'minor' | 'unassessed'; source: string };
  priority: 'needs-triage';
  test: { title: string; file: string; line: number; project: string; tags: string[] };
  reproductionSteps: string[];
  expectedResult: { fromTestCase: string[]; fromAssertion?: string };
  actualResult: { fromAssertion?: string; error: string };
  environment: {
    testEnv: string;
    baseURL?: string;
    browser: string;
    viewport?: string;
    os: string;
    playwright: string;
    buildRevision: string;
    frameworkCommit: string;
    ciRunUrl?: string;
  };
  evidence: { name: string; path?: string; contentType: string }[];
  consoleErrors: string[];
  networkFailures: string[];
  attempts: number;
  createdAt: string;
}

export function suggestSeverity(tags: readonly string[]): BugDraft['severity'] {
  if (tags.includes('@critical')) return { suggested: 'critical', source: 'tag @critical' };
  if (tags.includes('@smoke')) return { suggested: 'major', source: 'tag @smoke (core path)' };
  if (tags.includes('@minor')) return { suggested: 'minor', source: 'tag @minor' };
  return { suggested: 'unassessed', source: 'no severity tag' };
}

const list = (items: readonly string[], ordered = false) =>
  items.length ? items.map((s, i) => `${ordered ? `${i + 1}.` : '-'} ${s}`).join('\n') : '_None recorded._';

export function toMarkdown(d: BugDraft): string {
  const env = d.environment;
  return `# [DRAFT] ${d.title}

> Generated by the framework. **Not filed.** A person must confirm it is a product defect,
> check for duplicates (fingerprint \`${d.fingerprint}\`) and set priority before filing.

| Field | Value |
|---|---|
| Run ID | \`${d.runId}\` |
| Test case | ${d.testCaseIds.join(', ') || '—'} |
| Linked bugs | ${d.linkedBugs.join(', ') || '—'} |
| Classification | \`${d.classification.category}\` — ${d.classification.reason} |
| Consistent across attempts | ${d.classification.consistent ? 'yes' : 'no'} (${d.attempts} attempt(s)) |
| Severity (suggested) | ${d.severity.suggested} (${d.severity.source}) |
| Priority | ${d.priority} |
| Test | \`${d.test.file}:${d.test.line}\` — ${d.test.title} |

## Reproduction steps
${list(d.reproductionSteps, true)}

## Expected result
${list(d.expectedResult.fromTestCase)}
${d.expectedResult.fromAssertion ? `\nAssertion expected: \`${d.expectedResult.fromAssertion}\`` : ''}

## Actual result
${d.actualResult.fromAssertion ? `Assertion received: \`${d.actualResult.fromAssertion}\`\n` : ''}
\`\`\`text
${d.actualResult.error}
\`\`\`

## Environment
| | |
|---|---|
| Test environment | ${env.testEnv} |
| Base URL | ${env.baseURL ?? '—'} |
| Browser / viewport | ${env.browser} / ${env.viewport ?? '—'} |
| OS | ${env.os} |
| Playwright | ${env.playwright} |
| App build revision | ${env.buildRevision} |
| Framework commit | ${env.frameworkCommit} |
| CI run | ${env.ciRunUrl ?? 'local run'} |

## Evidence
${list(d.evidence.map((e) => `${e.name}${e.path ? `: \`${e.path}\`` : ''}`))}

### Console errors
${list(d.consoleErrors)}

### Network failures
${list(d.networkFailures)}
`;
}
